"""Compact desktop workspace and collapsible source controls."""
from PySide6.QtCore import Qt
from PySide6.QtWidgets import (QWidget, QLabel, QPushButton, QVBoxLayout,
    QHBoxLayout, QGridLayout, QScrollArea)


def label(text, name):
    widget = QLabel(text)
    widget.setObjectName(name)
    widget.setWordWrap(True)
    return widget


def build_workspace(w, layout):
    layout.setContentsMargins(0, 0, 0, 0)
    layout.setSpacing(0)
    header = QWidget()
    header.setObjectName('appHeader')
    row = QHBoxLayout(header)
    row.setContentsMargins(14, 6, 16, 6)
    row.setSpacing(14)
    w.sidebar_toggle = QPushButton('☰')
    w.sidebar_toggle.setObjectName('sidebarToggle')
    w.sidebar_toggle.setFixedSize(36, 36)
    w.sidebar_toggle.setCheckable(True)
    w.sidebar_toggle.setChecked(True)
    row.addWidget(w.sidebar_toggle)
    row.addWidget(label('◈', 'brandMark'))
    row.addWidget(label('PoseForge', 'brand'))
    row.addWidget(label('STUDIO', 'headerTag'))
    row.addStretch()
    row.addWidget(label('Nhận diện tư thế trực tiếp', 'muted'))
    layout.addWidget(header)

    shell = QHBoxLayout()
    shell.setSpacing(0)
    layout.addLayout(shell, 1)
    sidebar = QWidget()
    sidebar.setObjectName('sidebar')
    side = QVBoxLayout(sidebar)
    side.setContentsMargins(18, 22, 18, 18)
    side.setSpacing(12)
    side.addWidget(label('Thiết lập phiên', 'sectionTitle'))
    side.addWidget(label('Kết nối nguồn và chọn mô hình.', 'muted'))
    side.addSpacing(12)
    side.addWidget(label('01  /  NGUỒN HÌNH ẢNH', 'eyebrow'))
    w.source.setMinimumWidth(0)
    w.source.setToolTip('Chỉ số camera, đường dẫn video hoặc URL HTTP / RTSP.')
    side.addWidget(w.source)
    w.browse.setText('↗  Mở video')
    side.addWidget(w.browse)
    actions = QHBoxLayout()
    actions.setSpacing(8)
    w.add_button.setText('+ Thêm nguồn')
    w.remove_button.setText('− Bỏ nguồn')
    actions.addWidget(w.add_button)
    actions.addWidget(w.remove_button)
    side.addLayout(actions)
    w.extra_sources = []
    w.source_names = label('1 nguồn chính · Tối đa 4 nguồn', 'muted')
    side.addWidget(w.source_names)
    side.addWidget(label('Webcam / DroidCam / Video / RTSP', 'hint'))
    side.addSpacing(18)
    side.addWidget(label('02  /  MÔ HÌNH', 'eyebrow'))
    w.model.setMinimumWidth(0)
    side.addWidget(w.model)
    w.cpu_button = QPushButton('CPU · Không cần GPU')
    w.cpu_button.setCheckable(True)
    w.cpu_button.setChecked(w.options['device'] == 'cpu')
    w.cpu_button.setToolTip('Chạy trên CPU. Có thể chọn CUDA trong cài đặt nâng cao.')
    w.cpu_button.clicked.connect(w.select_cpu)
    side.addWidget(w.cpu_button)
    w.advanced.setText('⚙  Cài đặt nâng cao')
    side.addWidget(w.advanced)
    side.addStretch(1)
    side.addWidget(label('GÓC MÁY TỐT HƠN', 'eyebrow'))
    side.addWidget(label('Đặt camera ngang tầm mắt, để vai và tay nằm trong khung hình.', 'guide'))
    side.addWidget(label('POSEFORGE  /  DESKTOP', 'hint'))
    w.sidebar = QScrollArea()
    w.sidebar.setObjectName('sidebarScroll')
    w.sidebar.setWidgetResizable(True)
    w.sidebar.setFixedWidth(272)
    w.sidebar.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
    w.sidebar.setFrameShape(QScrollArea.Shape.NoFrame)
    w.sidebar.setWidget(sidebar)
    shell.addWidget(w.sidebar)

    def toggle_sidebar(expanded):
        w.sidebar.setVisible(expanded)
        action = 'Ẩn thanh bên' if expanded else 'Mở thanh bên'
        w.sidebar_toggle.setAccessibleName(action)
        w.sidebar_toggle.setToolTip(action)
    w.sidebar_toggle.toggled.connect(toggle_sidebar)
    toggle_sidebar(True)

    main = QWidget()
    main.setObjectName('workspace')
    content = QVBoxLayout(main)
    content.setContentsMargins(12, 10, 12, 8)
    content.setSpacing(8)
    shell.addWidget(main, 1)
    toolbar = QHBoxLayout()
    titles = QVBoxLayout()
    titles.setSpacing(3)
    titles.addWidget(label('Không gian quan sát', 'pageTitle'))
    toolbar.addLayout(titles, 1)
    w.start_button.setText('▶  Bắt đầu')
    w.start_button.setObjectName('primary')
    w.end_button.setText('■  Kết thúc')
    w.end_button.setObjectName('danger')
    toolbar.addWidget(w.start_button)
    toolbar.addWidget(w.end_button)
    w.status = label('READY', 'status')
    w.status.setMaximumWidth(340)
    toolbar.insertWidget(1, w.status)
    content.addLayout(toolbar)
    # Retained for session lifecycle compatibility; onboarding is in the empty stage.
    w.intro_cards = QWidget(main)
    w.intro_cards.hide()
    w.scroll = QScrollArea()
    w.scroll.setWidgetResizable(True)
    w.scroll.setFrameShape(QScrollArea.Shape.NoFrame)
    w.grid_widget = QWidget()
    w.grid_widget.setObjectName('cameraGrid')
    w.grid = QGridLayout(w.grid_widget)
    w.grid.setContentsMargins(0, 0, 0, 0)
    w.grid.setSpacing(14)
    w.scroll.setWidget(w.grid_widget)
    content.addWidget(w.scroll, 1)
    w.empty = QWidget()
    w.empty.setObjectName('previewStage')
    empty = QVBoxLayout(w.empty)
    empty.setContentsMargins(28, 24, 28, 24)
    empty.addWidget(label('CAMERA PREVIEW', 'eyebrow'))
    empty.addStretch()
    for text, name in [('◎', 'viewSymbol'), ('Sẵn sàng cho góc nhìn mới', 'emptyTitle'),
                       ('Chọn camera hoặc mở video từ thanh bên,\nsau đó nhấn Bắt đầu để nhận diện tư thế.', 'muted')]:
        item = label(text, name)
        item.setAlignment(Qt.AlignmentFlag.AlignCenter)
        empty.addWidget(item)
    empty.addSpacing(22)
    steps = QHBoxLayout()
    steps.addStretch()
    for text in ['01  Chọn nguồn', '02  Chọn mô hình', '03  Bắt đầu']:
        steps.addWidget(label(text, 'step'))
    steps.addStretch()
    empty.addLayout(steps)
    empty.addStretch()
    empty.addWidget(label('Camera chỉ được kết nối khi bạn bắt đầu phiên.', 'hint'))
    w.grid.addWidget(w.empty, 0, 0)
    w.output = label('Lưu trên thiết bị · Ghi video đang tắt', 'footer')
    w.output.setMaximumHeight(34)
    content.addWidget(w.output)
